import React, { useState } from 'react';
import { Bot, MessageSquare, Plus, Trash2, Code2, Sparkles, Copy, Check, Zap, ArrowRight } from 'lucide-react';
import { sound } from '../services/soundEffects';

interface DialogueNode {
  id: string;
  npcText: string;
  options: {
    playerReply: string;
    nextAction: string;
  }[];
}

export const NpcDialogueArchitect: React.FC = () => {
  const [npcName, setNpcName] = useState('Cyber Sensei KAI');
  const [npcPersonality, setNpcPersonality] = useState('Mentor cybernetic bijak yang melatih hacker muda');
  const [nodes, setNodes] = useState<DialogueNode[]>([
    {
      id: 'node-1',
      npcText: 'Selamat datang di Grid Blox, petualang. Sistem mainframe membutuhkan keahlianmu.',
      options: [
        { playerReply: 'Bagaimana cara mendapatkan AI Neurons?', nextAction: 'Buka Quest Penambangan Data' },
        { playerReply: 'Saya siap untuk tantangan Obby!', nextAction: 'Teleport ke Stage 1' },
        { playerReply: 'Hanya melihat-lihat.', nextAction: 'Tutup Dialog' }
      ]
    }
  ]);
  const [copied, setCopied] = useState(false);
  const [isAiGenerating, setIsAiGenerating] = useState(false);

  const handleGenerateAiQuest = () => {
    setIsAiGenerating(true);
    sound.playClick();

    setTimeout(() => {
      setNodes([
        {
          id: 'node-1',
          npcText: `Protokol Darurat aktif! Firewall level 4 sedang diserang oleh Rogue Glitch Bot. Maukah kamu membantuku mengambil alih kendali server?`,
          options: [
            { playerReply: 'Tentu, apa senjataku?', nextAction: 'Beri Cyber-Katana & Quest Mainframe' },
            { playerReply: 'Berapa banyak Robux/Neurons hadiahnya?', nextAction: 'Tampilkan Reward 500 Neurons' },
            { playerReply: 'Terlalu berbahaya untukku.', nextAction: 'Nasihat Motivasi NPC' }
          ]
        },
        {
          id: 'node-2',
          npcText: `Ambil Cyber-Katana ini. Tebas 5 Glitch Bot di Neon Plaza dan bawa kembali 3 Quantum Cores kepadaku!`,
          options: [
            { playerReply: 'Misi diterima! Berangkat sekarang.', nextAction: 'StartQuest(Firewall_Protocol)' },
            { playerReply: 'Beri aku tips bertarung terlebih dahulu.', nextAction: 'Tampilkan Tutorial Parry' }
          ]
        }
      ]);
      setIsAiGenerating(false);
      sound.playSuccess();
    }, 600);
  };

  const getExportedLuauCode = () => {
    return `--!strict
-- ReplicatedStorage/NPCs/${npcName.replace(/\s+/g, '_')}_Dialogue.luau
-- Generated by Roblox AI Nexus NPC Architect

local DialogueTree = {
    NPCName = "${npcName}",
    Personality = "${npcPersonality}",
    Nodes = {
${nodes.map((n, i) => `        ["${n.id}"] = {
            Prompt = "${n.npcText.replace(/"/g, '\\"')}",
            Choices = {
${n.options.map(o => `                { Text = "${o.playerReply.replace(/"/g, '\\"')}", CallbackAction = "${o.nextAction}" },`).join('\n')}
            }
        },`).join('\n')}
    }
}

return DialogueTree`;
  };

  const handleCopyLuau = () => {
    navigator.clipboard.writeText(getExportedLuauCode());
    setCopied(true);
    sound.playClick();
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="grid grid-cols-1 lg:grid-cols-12 gap-5">
      {/* Settings & Nodes Left */}
      <div className="lg:col-span-6 bg-[#14161c] rounded-2xl border border-[#262a35] p-5 shadow-xl flex flex-col gap-5">
        <div className="flex items-center justify-between pb-3 border-b border-[#262a35]">
          <div className="flex items-center gap-2">
            <Bot className="w-5 h-5 text-[#00e5ff]" />
            <h2 className="font-fredoka text-lg font-bold text-white">Roblox AI NPC Architect</h2>
          </div>

          <button
            onClick={handleGenerateAiQuest}
            disabled={isAiGenerating}
            className="px-3.5 py-1.5 rounded-xl bg-gradient-to-r from-[#00e5ff] to-[#0088ff] text-black font-fredoka font-bold text-xs flex items-center gap-1.5 shadow-sm active:scale-95 disabled:opacity-50"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>Generate AI Dialogue</span>
          </button>
        </div>

        {/* NPC Configuration */}
        <div className="space-y-3">
          <div>
            <label className="text-xs text-gray-400 block mb-1">Nama NPC:</label>
            <input
              type="text"
              value={npcName}
              onChange={(e) => setNpcName(e.target.value)}
              className="w-full bg-[#0e1014] border border-[#2a2e3a] focus:border-[#00e5ff] rounded-xl px-3 py-2 text-xs text-white focus:outline-none"
            />
          </div>

          <div>
            <label className="text-xs text-gray-400 block mb-1">Kepribadian &amp; Peran:</label>
            <input
              type="text"
              value={npcPersonality}
              onChange={(e) => setNpcPersonality(e.target.value)}
              className="w-full bg-[#0e1014] border border-[#2a2e3a] focus:border-[#00e5ff] rounded-xl px-3 py-2 text-xs text-white focus:outline-none"
            />
          </div>
        </div>

        {/* Interactive Dialogue Nodes */}
        <div className="space-y-3">
          <div className="text-xs font-bold uppercase tracking-wider text-gray-300">
            Percakapan &amp; Opsi Respon Pemain
          </div>

          {nodes.map((node, nodeIdx) => (
            <div key={node.id} className="p-4 rounded-xl bg-[#191b22] border border-[#262a35] space-y-3">
              <div>
                <span className="text-[11px] font-mono-code text-[#00e5ff] block mb-1">Ucapan NPC:</span>
                <textarea
                  value={node.npcText}
                  onChange={(e) => {
                    const next = [...nodes];
                    next[nodeIdx].npcText = e.target.value;
                    setNodes(next);
                  }}
                  rows={2}
                  className="w-full bg-[#0d0f14] border border-[#252834] rounded-lg p-2.5 text-xs text-white focus:outline-none"
                />
              </div>

              <div>
                <span className="text-[11px] font-mono-code text-gray-400 block mb-1.5">Pilihan Jawaban Pemain:</span>
                <div className="space-y-2">
                  {node.options.map((opt, optIdx) => (
                    <div key={optIdx} className="flex items-center gap-2 text-xs">
                      <span className="text-gray-500 font-mono-code">{optIdx + 1}.</span>
                      <input
                        type="text"
                        value={opt.playerReply}
                        onChange={(e) => {
                          const next = [...nodes];
                          next[nodeIdx].options[optIdx].playerReply = e.target.value;
                          setNodes(next);
                        }}
                        className="flex-1 bg-[#0d0f14] border border-[#252834] rounded-lg px-2.5 py-1.5 text-xs text-gray-200 focus:outline-none"
                      />
                      <ArrowRight className="w-3.5 h-3.5 text-[#00ff88] shrink-0" />
                      <input
                        type="text"
                        value={opt.nextAction}
                        onChange={(e) => {
                          const next = [...nodes];
                          next[nodeIdx].options[optIdx].nextAction = e.target.value;
                          setNodes(next);
                        }}
                        className="w-36 bg-[#0d0f14] border border-[#252834] rounded-lg px-2.5 py-1.5 text-xs text-[#00ff88] font-mono-code focus:outline-none"
                      />
                    </div>
                  ))}
                </div>
              </div>
            </div>
          ))}
        </div>
      </div>

      {/* Code Export Right */}
      <div className="lg:col-span-6 bg-[#14161c] rounded-2xl border border-[#262a35] p-5 shadow-xl flex flex-col justify-between">
        <div>
          <div className="flex items-center justify-between pb-3 border-b border-[#262a35] mb-3">
            <div className="flex items-center gap-2">
              <Code2 className="w-4 h-4 text-[#00e5ff]" />
              <span className="font-mono-code text-xs text-white font-bold">Generated Luau Module</span>
            </div>

            <button
              onClick={handleCopyLuau}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[#222631] hover:bg-[#2b303d] text-gray-300 text-xs font-medium transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-green-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Tersalin' : 'Salin Luau Module'}</span>
            </button>
          </div>

          <div className="p-4 bg-[#0a0b0e] rounded-xl font-mono-code text-xs leading-relaxed max-h-[500px] overflow-auto border border-[#1f232d]">
            <pre className="text-gray-300">
              <code>{getExportedLuauCode()}</code>
            </pre>
          </div>
        </div>

        <div className="mt-4 p-3 rounded-xl bg-[#191b22] border border-[#262a35] text-xs text-gray-400 flex items-center justify-between">
          <span>Siap di-import langsung ke Roblox Studio ReplicatedStorage!</span>
          <span className="text-[#00ff88] font-mono-code">Rojo Ready</span>
        </div>
      </div>
    </div>
  );
};
